const DICTIONARIES = { 'zh-CN': zh, en };

// exported for the test-suite: "is every key translated?"
export const DICT_ZH = zh;
export const DICT_EN = en;

/** Normalise anything a browser sends into a locale we actually ship. */
export function normaliseLocale(input) {
  if (!input) return null;
  const raw = String(input).toLowerCase();
  if (raw.startsWith('zh')) return 'zh-CN';
  if (raw.startsWith('en')) return 'en';
  return null;
}

export function availableLocales() {
  return Object.entries(LOCALES).map(([code, meta]) => ({ code, ...meta }));
}

export function localeMeta(code) {
  return LOCALES[code] || LOCALES[DEFAULT_LOCALE];
}

/**
 * Pick a locale for a request: explicit ?lang= wins, then the cookie the
 * language switcher sets, then the site config, then Accept-Language.
 */
export function resolveLocale(req, fallback = DEFAULT_LOCALE) {
  const fromQuery = normaliseLocale(req.query && req.query.lang);
  if (fromQuery) return fromQuery;
  const cookies = req.cookies || {};
  const fromCookie = normaliseLocale(cookies.oldie_lang);
  if (fromCookie) return fromCookie;
  const header = String(req.headers['accept-language'] || '');
  for (const part of header.split(',')) {
    const hit = normaliseLocale(part.split(';')[0].trim());
    if (hit) return hit;
  }
  return normaliseLocale(fallback) || DEFAULT_LOCALE;
}

export function makeTranslator(code) {
  const dict = DICTIONARIES[code] || DICTIONARIES[DEFAULT_LOCALE];
  const fallbackDict = DICTIONARIES[DEFAULT_LOCALE];
  const t = (key, vars) => {
    let out = dict[key];
    if (out === undefined) out = fallbackDict[key];
    if (out === undefined) return key;
    if (vars && typeof vars === 'object') {
      for (const [k, v] of Object.entries(vars)) out = out.split('{' + k + '}').join(String(v));
    }
    return out;
  };
  t.locale = code;
  t.has = (key) => dict[key] !== undefined || fallbackDict[key] !== undefined;
  return t;
}

/** Strings the browser needs (toasts, radio label, editor hints). */
